-- 2단계: 운세 문구뱅크 테이블 + 초기 시딩

CREATE TABLE fortune_content_bank (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  category TEXT NOT NULL CHECK (category IN ('사업운','매출운','거래운')),
  relation_type TEXT NOT NULL CHECK (relation_type IN ('생','극','합','충','비화')),
  tone TEXT NOT NULL CHECK (tone IN ('길','중','흉')),
  content TEXT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE fortune_content_bank ENABLE ROW LEVEL SECURITY;

CREATE POLICY fortune_bank_select_all ON fortune_content_bank
  FOR SELECT USING (is_active = true);

-- 관리자 쓰기 정책: 기존 qd_is_admin() 헬퍼 재사용 (20260907050000_admin_role_rls.sql)
CREATE POLICY fortune_bank_admin_all ON fortune_content_bank
  FOR ALL USING (qd_is_admin())
  WITH CHECK (qd_is_admin());

