-- ============================================================
-- users 테이블의 중복 INSERT 정책 제거 (보안 구멍 재수정)
-- 대상 테이블: users
-- Supabase SQL Editor에 그대로 붙여넣어 실행하세요. (재실행해도 안전 -
-- drop policy if exists)
--
-- 배경) 20260908140000에서 users_insert_own에 role in ('buyer','partner')
-- 검증을 추가했는데도 role:'admin' self-insert가 여전히 뚫리는 문제가
-- 있었음. 원인을 pg_policy로 직접 조회해서 찾음: 이 리포의 마이그레이션
-- 파일 어디에도 없는, 한글 이름의 별도 INSERT 정책
-- "본인 회원 정보 등록"이 users 테이블에 남아 있었고, 그 with_check가
-- `auth.uid() = id`뿐이라 role 값을 전혀 검증하지 않았음. RLS는 같은
-- 커맨드(INSERT)에 여러 PERMISSIVE 정책이 있으면 그중 하나만 통과해도
-- 되므로(OR 결합), users_insert_own을 아무리 강화해도 이 중복 정책이
-- role 제한 없이 계속 통과시켜준 것 - 20260908130000 작업 당시
-- 마이그레이션 파일 목록에서 이 정책의 존재를 놓쳤음(이 리포의
-- 마이그레이션 파일 = 실제 DB 스키마의 100% 정확한 기록이 아니라는
-- HANDOFF.md의 기존 경고와 같은 종류의 문제 - 이번엔 컬럼이 아니라
-- 정책이 리포에 기록되지 않은 채로 있었던 경우).
--
-- 조치) 이 중복 정책을 삭제. "본인 회원 정보 등록"이 하던 일(본인 id로
-- 회원가입 시 자기 행 insert)은 이미 users_insert_own이 role 검증까지
-- 포함해서 동일하게 수행하므로 기능 손실 없음.
-- ============================================================

drop policy if exists "본인 회원 정보 등록" on users;
